"""Robot-specific face/cloth selections and reproducible game material bake."""
import io
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
from glb2iqm import Glb


def image(g, texture):
    im = g.j['images'][g.j['textures'][texture]['source']]
    v = g.j['bufferViews'][im['bufferView']]; start = v.get('byteOffset', 0)
    return Image.open(io.BytesIO(g.bin[start:start + v['byteLength']])).convert('RGB')


def selections(g):
    pr = g.j['meshes'][0]['primitives'][0]; at = pr['attributes']
    p = g.acc(at['POSITION']); uv = g.acc(at['TEXCOORD_0']); tri = g.acc(pr['indices']).reshape(-1, 3).astype(int)
    mat = g.j['materials'][pr['material']]['pbrMetallicRoughness']
    tex = image(g, mat['baseColorTexture']['index']); rgb = np.array(tex)
    c = rgb[np.clip((uv[:, 1] * tex.height).astype(int), 0, tex.height-1), np.clip((uv[:, 0] * tex.width).astype(int), 0, tex.width-1)].astype(float)
    gold = (c[:, 0] > c[:, 1]*1.13) & (c[:, 1] > c[:, 2]*1.25)
    center = p[tri].mean(1)
    cloth = (gold[tri].sum(1) >= 2) & (center[:, 2] < -.085) & (center[:, 1] > .58)
    # Dark fringe triangles at the far tip have no gold texels.
    cloth |= (center[:, 2] < -.25) & (center[:, 1] > .58)
    # Remove the old rear flap and shoulder stump, preserving the front wrap.
    rear = (center[:,0] < -.055) | ((center[:,0] < .005) & (center[:,2] < -.02))
    cloth |= (gold[tri].sum(1) >= 2) & rear & (center[:,1] > .77) & (center[:,1] < .88)
    eyes = (gold[tri].sum(1) >= 2) & (center[:, 1] > .875) & (center[:, 1] < .912) & (center[:, 0] > .075)
    return tri, cloth, eyes, uv, tex


def finish_geometry(g, P, N, U, JI, W, tris, names, ibm, scale):
    """Trim the original rear flap and graft a folded, neck-skinned attachment.

    Socket coordinates are generated in the exported bone's local frame; cgame
    uses exactly these coordinates, avoiding independent hand-tuned offsets.
    """
    _, removed, _, _, tex = selections(g)
    tris = tris[~removed]
    swap = np.array([[0,0,1],[1,0,0],[0,1,0]],float)
    neck = names.index('neck_01')
    bind = np.linalg.inv(ibm[neck])
    origin = swap @ bind[:3,3] * scale
    rotation = swap @ bind[:3,:3] @ swap.T
    # Quake-space cross sections: broad overlap buried in the old neck wrap,
    # a small folded knot, then the narrow exit shared by the physics ribbon.
    rings = [(-4.2, 54.0, 3.0, .8), (-6.4, 53.7, 3.2, 1.0),
             (-9.0, 52.5, 2.7, .65), (-10.8, 51.8, 2.4, .35)]
    q=[]
    for x,z,width,depth in rings:
        q.extend([(x-depth,-width,z),(x-depth,width,z),
                  (x+depth,width,z),(x+depth,-width,z)])
    q=np.array(q); faces=[]
    for ring in range(len(rings)-1):
        for j in range(4):
            a=ring*4+j;b=ring*4+(j+1)%4;c=b+4;d=a+4
            faces.extend([(a,b,c),(a,c,d)])
    # End face is overlapped by the pinned cloth edge, hiding small numerical gaps.
    faces.extend([(12,14,13),(12,15,14)])
    faces=np.array(faces)
    root=np.array([-10.8,0,51.8]); local=np.linalg.solve(rotation,root-origin)
    side=np.linalg.solve(rotation,np.array([0,1,0])); back=np.linalg.solve(rotation,np.array([-1,0,0]))
    header='// Generated by robot_finish.finish_geometry; shared with the baked scarf socket.\n'
    for name,value in [('robotScarfSocket',local),('robotScarfSide',side),('robotScarfBack',back)]:
        header+='static const vec3_t '+name+' = { '+', '.join(f'{v:.8f}f' for v in value)+' };\n'
    localVerts=np.linalg.solve(rotation,(q-origin).T).T
    header+='static const vec3_t robotScarfJoinVerts[] = {\n'
    header+=''.join('    { '+', '.join(f'{v:.8f}f' for v in row)+' },\n' for row in localVerts)+'};\n'
    header+='static const int robotScarfJoinTris[][3] = {\n'
    header+=''.join('    { '+', '.join(str(v) for v in row)+' },\n' for row in faces)+'};\n'
    (Path(__file__).resolve().parents[2]/'engine/code/cgame/cg_robotscarf.h').write_text(header)
    print('Scarf join: trimmed',removed.sum(),'triangles; generated',len(faces),'neck-bound cloth faces')
    return P, N, U, JI, W, tris



def bake(source, out):
    g = Glb(source); out = Path(out); out.mkdir(parents=True, exist_ok=True)
    tri, cloth, eyes, uv, tex = selections(g)
    mask = Image.new('L', tex.size); draw = ImageDraw.Draw(mask)
    for t in tri[eyes]:
        draw.polygon([tuple(v) for v in uv[t] * tex.size], fill=255)
    mask = mask.filter(ImageFilter.MaxFilter(3))
    emission = Image.new('RGB', tex.size, (0, 0, 0))
    emission.paste((255, 190, 55), mask=mask)
    emission.resize((1024,1024), Image.Resampling.LANCZOS).save(out/'robot_e.png')
    pr=g.j['meshes'][0]['primitives'][0]; m=g.j['materials'][pr['material']]
    mr=np.array(image(g,m['pbrMetallicRoughness']['metallicRoughnessTexture']['index'])).astype(float)/255
    rough=np.maximum(mr[:,:,1]*(1-.55*mr[:,:,2]),.18*mr[:,:,2]); metal=mr[:,:,2]
    pbr=np.zeros((*rough.shape,3));pbr[:,:,0]=1-rough;pbr[:,:,1]=metal
    Image.fromarray(np.uint8(np.round(pbr*255))).resize((1024,1024),Image.Resampling.LANCZOS).save(out/'robot_pbr.png')
    spec=np.zeros((*rough.shape,4));spec[:,:,:3]=(.04+.56*metal)[:,:,None];spec[:,:,3]=1-rough
    Image.fromarray(np.uint8(np.round(spec*255))).resize((1024,1024),Image.Resampling.LANCZOS).save(out/'robot_s.tga')
    # Deterministic woven cloth with ragged sides, split tips and small tears.
    y,x=np.indices((512,128)); u=x/127.; v=y/511.
    rng=np.random.default_rng(64)
    weave=np.clip(210+12*np.sin(x*2.4)+7*np.sin(y*2.7)+rng.normal(0,5,x.shape),0,255)
    left=.025+.016*np.sin(v*91)+.012*np.sin(v*173)
    right=.975-.018*np.sin(v*79)**2-.012*np.sin(v*151)**2
    tips=.89+.075*np.sin(u*27)+.025*np.sin(u*93)
    keep=(u>left)&(u<right)&(v<tips)
    keep &= ~((v>.74)&(np.abs(u-(.48+.018*np.sin(v*29)))<.015+(v-.74)*.12))
    for cx,cy,rx,ry in [(.12,.48,.025,.045),(.83,.66,.018,.035),(.24,.79,.014,.05)]:
        keep &= ((u-cx)/rx)**2+((v-cy)/ry)**2>1
    rgba=np.empty((512,128,4),dtype=np.uint8)
    rgba[:,:,:3]=weave[:,:,None];rgba[:,:,3]=keep*255
    Image.fromarray(rgba).save(out/'robot_cloth.png')
    shader='models/s64/robot_cloth\n{\n cull none\n { clampmap models/s64/robot_cloth.png\n alphaFunc GE128\n depthWrite\n rgbGen vertex\n }\n}\n'
    shader+='models/s64/robot_cloth_join\n{\n cull none\n { map models/s64/robot_cloth.png\n rgbGen vertex\n }\n}\n'
    for name,filename in [('robot','robot_s.tga'),('robot_pbr','robot_pbr.png')]:
        shader += f'''models/s64/{name}
{{
 cull none
 {{ map models/s64/robot.jpg
 rgbGen lightingDiffuse
 }}
 {{ stage normalMap
 map models/s64/robot_n.jpg
 }}
 {{ stage specularMap
 map models/s64/{filename}
 }}
 {{ map models/s64/robot_e.png
 blendFunc GL_ONE GL_ONE
 rgbGen identity
 }}
}}
'''
    (out.parent.parent/'scripts'/'s64_robot.shader').write_text(shader)
    print('Removed scarf triangles:',int(cloth.sum()),'eye triangles:',int(eyes.sum()))

if __name__=='__main__':
    import sys
    bake(*sys.argv[1:3])
